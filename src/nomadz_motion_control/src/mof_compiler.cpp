  bool MofCompiler::compileMotionFiles(char* buffer, size_t size) {
    print_buffer_ = buffer;
    print_buffer_size_ = size;
    print_buffer_[0] = 0;

    num_of_labels_ = 0;
    num_of_lines_ = 0;
    num_of_files_ = 0;

    std::memset(label_number_, 0, sizeof(label_number_));
    std::memset(motion_, 0, sizeof(motion_));
    std::memset(line_number_, 0, sizeof(line_number_));
    std::memset(line_motion_id_, 0, sizeof(line_motion_id_));
    std::memset(file_start_index_, 0, sizeof(file_start_index_));

    label_motion_[num_of_labels_] = strdup("extern");
    label_name_[num_of_labels_] = strdup("start");
    label_number_[num_of_labels_++] = static_cast<short>(num_of_lines_);

    line_data_[num_of_lines_] = strdup("transition allMotions extern start");
    line_number_[num_of_lines_++] = 1;

    if (!parseMotionFiles() || !parseExternMotionFile()) {
      return false;
    }

    // check whether the last line of every mof is an unconditional jump
    for (int i = 1; i <= num_of_files_; ++i) {
      int ind = i < num_of_files_ ? file_start_index_[i] - 1 : num_of_lines_ - 1;
      if (strncmp(line_data_[ind], "transition allMotions", 21) != 0) {
        myprintf(
          "%s(%i) : error: this mof does not end with a transition for allMotions\n", file_name_[i - 1], line_number_[ind]);
        return false;
      }
    }

    // check whether there are mofs without SpecialActionRequest::SpecialAction
    for (int i = 1; i < num_of_labels_; ++i) {
      if (strcmp(label_motion_[i], label_motion_[i - 1]) == 0) {
        continue;
      }
      bool found = false;
      for (int j = 0; j < NUM_SPECIAL_ACTIONS; ++j) {
        if (strcmp(label_motion_[i], mof_file_map_.left.at(static_cast<SpecialActionType>(j)).c_str()) == 0) {
          found = true;
          break;
        }
      }
      if (!found) {
        for (int j = num_of_files_ - 1; j >= 0; --j) {
          if (file_start_index_[j] <= label_number_[i]) {
            myprintf("%s(%i) : warning: there is no special action id for this mof\n", file_name_[j], 1);
            break;
          }
        }
      }
    }
    return generateMotionNet();
  }
